  _stopBobTween() {
    if (this.bobTween) {
      this.bobTween.stop();
      this.bobTween = null;
    }
  }

  _stopPhaseTimer() {
    if (this.phaseTimer) {
      this.phaseTimer.remove(false);
      this.phaseTimer = null;
    }
    if (this.biteTimer) {
      this.biteTimer.remove(false);
      this.biteTimer = null;
    }
  }

  _cancelAllPhaseLogic() {
    this._stopPhaseTimer();
    this._stopTroll();
    this._stopBobTween();
    if (this.nibbleTween) {
      this.nibbleTween.stop();
      this.nibbleTween = null;
    }
    if (this.activeCastTween) {
      this.activeCastTween.stop();
      this.activeCastTween = null;
    }
    this._endFight();
    if (this.reelOverlay) {
      this.reelOverlay.destroy();
      this.reelOverlay = null;
    }
    this.reelEnd = null;
    this.lure = null;
    this._resetLureSprite();
  }
