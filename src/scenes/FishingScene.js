  _buildWaterlineOverlay() {
    // Toggle with 'W': where casts are allowed -- the water below the
    // map's waterline in cyan, the jetty or pier cut out of it in red --
    // and the landing spot (data/maps.js).
    this.waterBoundsDebug = this.add.graphics();
    this.waterBoundsDebug.setDepth(99);
    this.waterBoundsDebug.setVisible(false);
    this._redrawWaterCurve();

    this.input.keyboard?.on('keydown-W', () => {
      this.waterBoundsDebug.setVisible(!this.waterBoundsDebug.visible);
    });
  }

  _redrawWaterCurve() {
    const g = this.waterBoundsDebug;
    if (!g) return;
    g.clear();
    g.fillStyle(0x00ffff, 0.25);
    g.lineStyle(2, 0x00ffff, 0.9);
    const SAMPLES = 64;
    g.beginPath();
    g.moveTo(WORLD_LEFT, WORLD_BOTTOM);
    for (let i = 0; i <= SAMPLES; i++) {
      const x = WORLD_LEFT + (WORLD_WIDTH * i) / SAMPLES;
      g.lineTo(x, this.map.waterTopAt(x));
    }
    g.lineTo(WORLD_RIGHT, WORLD_BOTTOM);
    g.closePath();
    g.fillPath();
    g.strokePath();

    // ...minus the jetty or pier (and any floes), in red; and the landing
    // spot, a dot.
    for (const dry of this.map.dryParts) {
      g.fillStyle(0xff3030, 0.35);
      g.lineStyle(2, 0xff3030, 0.9);
      g.beginPath();
      g.moveTo(dry[0][0], dry[0][1]);
      for (const [x, y] of dry.slice(1)) g.lineTo(x, y);
      g.closePath();
      g.fillPath();
      g.strokePath();
    }
    g.fillStyle(0xffff00, 1);
    g.fillCircle(this.map.landing.x, this.map.landing.y, 6);
  }

